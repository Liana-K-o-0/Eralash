    def add_rules(self, filepath):
        with open(filepath, 'r', encoding='utf-8') as f:
            inf = json.load(f)
        new_rules = [Rule.new_rule(i) for i in inf.get("rules", [])]
        self.rules.extend(new_rules)
        self.rules.sort(key=lambda x: x.priority)
